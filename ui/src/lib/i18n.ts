export const dictionaries = { en, it };

/** First language in the Mac's list that the app supports, else English. */
export function pickLang(preferred: readonly string[]): Lang {
  for (const p of preferred) {
    const base = p.toLowerCase().split('-')[0];
    if (base === 'en' || base === 'it') return base;
  }
  return 'en';
}

export function format(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

// In development, `?lang=it` previews another language in a normal browser.
const devLang = import.meta.env?.DEV && typeof location !== 'undefined' ? new URLSearchParams(location.search).get('lang') : null;
const preferred = devLang ? [devLang] : typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language];
export const lang: Lang = pickLang(preferred);

/**
 * Locale for dates and times: the Mac's own locale when it matches the app
 * language (keeps the region's formats), otherwise the app language.
 */
export const dateLocale: string = preferred.find((p) => p.toLowerCase().startsWith(lang)) ?? lang;

export function t(key: Key, vars?: Record<string, string | number>): string {
  return format(dictionaries[lang][key], vars);
}
